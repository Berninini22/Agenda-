-- E-mails transacionais do Agenda+ (aplicação ativa: Supabase).
-- Execute após supabase-schema.sql. A implantação da Edge Function está em EMAIL-SETUP.md.

create extension if not exists pg_cron;
create extension if not exists pg_net with schema extensions;

create table if not exists public.notification_log (
  id bigint generated by default as identity primary key,
  user_id uuid references auth.users(id) on delete set null,
  appointment_id bigint references public.appointments(id) on delete set null,
  channel text not null check (channel in ('email','whatsapp')),
  event text not null,
  destination_masked text,
  status text not null default 'queued' check (status in ('queued','sent','failed','skipped')),
  provider_message_id text,
  error_code text,
  created_at timestamptz not null default now(),
  sent_at timestamptz,
  schedule_signature text not null default 'legacy',
  attempts integer not null default 0,
  next_attempt_at timestamptz not null default now(),
  locked_at timestamptz,
  last_error text
);

alter table public.notification_log
  add column if not exists schedule_signature text not null default 'legacy',
  add column if not exists attempts integer not null default 0,
  add column if not exists next_attempt_at timestamptz not null default now(),
  add column if not exists locked_at timestamptz,
  add column if not exists last_error text;

update public.notification_log
set schedule_signature = 'legacy-' || id::text
where channel='email' and schedule_signature='legacy';
update public.notification_log
set status='skipped', last_error='tipo_de_evento_legado_nao_processado'
where channel='email' and event not in ('CONFIRMACAO','LEMBRETE') and status in ('queued','failed');

create unique index if not exists notification_email_dedup_uq
  on public.notification_log(appointment_id, event, schedule_signature)
  where channel = 'email' and appointment_id is not null;
create index if not exists notification_email_due_idx
  on public.notification_log(next_attempt_at, created_at)
  where channel = 'email' and status in ('queued','failed');

alter table public.notification_log enable row level security;
revoke all on public.notification_log from anon;
grant select on public.notification_log to authenticated;
drop policy if exists "Usuário consulta seu histórico de notificações" on public.notification_log;
create policy "Usuário consulta seu histórico de notificações"
  on public.notification_log for select to authenticated using (auth.uid() = user_id);

-- Um registro de confirmação e um de lembrete para cada versão de data/hora.
create or replace function public.queue_appointment_emails_on_insert()
returns trigger language plpgsql security definer set search_path = public as $$
declare reminder_at timestamptz;
begin
  if coalesce(new.status, 'Confirmada') in ('Cancelada','cancelada','canceled') then return new; end if;
  insert into public.notification_log(user_id,appointment_id,channel,event,status,schedule_signature,next_attempt_at)
  values(new.user_id,new.id,'email','CONFIRMACAO','queued','CONFIRMACAO_V1',now())
  on conflict do nothing;
  reminder_at := (((new.date_iso - 1)::timestamp + time '09:00') at time zone 'America/Sao_Paulo');
  insert into public.notification_log(user_id,appointment_id,channel,event,status,schedule_signature,next_attempt_at)
  values(new.user_id,new.id,'email','LEMBRETE','queued',new.date_iso::text || 'T' || left(new.time,5),reminder_at)
  on conflict do nothing;
  return new;
end; $$;
drop trigger if exists appointments_queue_emails_insert on public.appointments;
create trigger appointments_queue_emails_insert after insert on public.appointments
for each row execute function public.queue_appointment_emails_on_insert();

create or replace function public.refresh_appointment_email_reminder()
returns trigger language plpgsql security definer set search_path = public as $$
declare reminder_at timestamptz;
begin
  if coalesce(new.status,'Confirmada') in ('Cancelada','cancelada','canceled') then
    update public.notification_log set status='skipped', last_error='consulta_cancelada', locked_at=null, next_attempt_at=now()
    where appointment_id=new.id and channel='email' and status in ('queued','failed');
    return new;
  end if;
  if old.date_iso is distinct from new.date_iso or old.time is distinct from new.time then
    update public.notification_log set status='skipped', last_error='consulta_reagendada', locked_at=null, next_attempt_at=now()
    where appointment_id=new.id and channel='email' and event='LEMBRETE' and status in ('queued','failed');
    reminder_at := (((new.date_iso - 1)::timestamp + time '09:00') at time zone 'America/Sao_Paulo');
    insert into public.notification_log(user_id,appointment_id,channel,event,status,schedule_signature,next_attempt_at)
    values(new.user_id,new.id,'email','LEMBRETE','queued',new.date_iso::text || 'T' || left(new.time,5),reminder_at)
    on conflict do nothing;
  end if;
  return new;
end; $$;
drop trigger if exists appointments_refresh_email_reminder on public.appointments;
create trigger appointments_refresh_email_reminder after update of date_iso,time,status on public.appointments
for each row execute function public.refresh_appointment_email_reminder();

create or replace function public.skip_appointment_emails_on_delete()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  update public.notification_log set status='skipped', last_error='consulta_excluida', locked_at=null, next_attempt_at=now()
  where appointment_id=old.id and channel='email' and status in ('queued','failed');
  return old;
end; $$;
drop trigger if exists appointments_skip_emails_delete on public.appointments;
create trigger appointments_skip_emails_delete before delete on public.appointments
for each row execute function public.skip_appointment_emails_on_delete();

-- Claim atômico com SKIP LOCKED; protege de cron/requests concorrentes e recupera locks antigos.
create or replace function public.claim_due_appointment_emails(
  p_appointment_id bigint default null,
  p_event text default null,
  p_user_id uuid default null,
  p_limit integer default 20
) returns table(id bigint, appointment_id bigint, user_id uuid, event text, schedule_signature text, attempts integer)
language plpgsql security definer set search_path = public as $$
begin
  return query
  with candidates as (
    select n.id
    from public.notification_log n
    join public.appointments a on a.id=n.appointment_id
    where n.channel='email'
      and n.event in ('CONFIRMACAO','LEMBRETE')
      and n.status in ('queued','failed')
      and n.attempts < 8
      and n.next_attempt_at <= now()
      and (n.locked_at is null or n.locked_at < now() - interval '15 minutes')
      and (p_appointment_id is null or n.appointment_id=p_appointment_id)
      and (p_event is null or n.event=p_event)
      and (p_user_id is null or n.user_id=p_user_id)
      and coalesce(a.status,'Confirmada') not in ('Cancelada','cancelada','canceled')
      and (n.event <> 'LEMBRETE' or a.date_iso = (now() at time zone 'America/Sao_Paulo')::date + 1)
    order by n.next_attempt_at,n.created_at
    for update of n skip locked
    limit greatest(1,least(coalesce(p_limit,20),100))
  )
  update public.notification_log n
    set locked_at=now(), attempts=n.attempts+1
  from candidates c
  where n.id=c.id
  returning n.id,n.appointment_id,n.user_id,n.event,n.schedule_signature,n.attempts;
end; $$;
revoke all on function public.claim_due_appointment_emails(bigint,text,uuid,integer) from public, anon, authenticated;
grant execute on function public.claim_due_appointment_emails(bigint,text,uuid,integer) to service_role;

-- O cron chama o dispatcher a cada cinco minutos. Os lembretes só ficam elegíveis às 09h locais do dia anterior.
-- Cadastre os 3 segredos uma vez no Vault, substituindo os placeholders. EMAIL_CRON_SECRET também vai para Edge Function Secrets.
select vault.create_secret('https://YOUR_PROJECT_REF.supabase.co','agenda_email_project_url');
select vault.create_secret('YOUR_SUPABASE_PUBLISHABLE_KEY','agenda_email_publishable_key');
select vault.create_secret('REPLACE_WITH_A_LONG_RANDOM_SECRET','agenda_email_cron_secret');
select cron.unschedule(jobid) from cron.job where jobname='agenda-email-dispatcher';
select cron.schedule(
  'agenda-email-dispatcher',
  '*/5 * * * *',
  $$
    select net.http_post(
      url := (select decrypted_secret from vault.decrypted_secrets where name='agenda_email_project_url') || '/functions/v1/appointment-emails',
      headers := jsonb_build_object(
        'Content-Type','application/json',
        'apikey',(select decrypted_secret from vault.decrypted_secrets where name='agenda_email_publishable_key'),
        'x-cron-secret',(select decrypted_secret from vault.decrypted_secrets where name='agenda_email_cron_secret')
      ),
      body := '{"scheduled":true}'::jsonb,
      timeout_milliseconds := 10000
    );
  $$
);
