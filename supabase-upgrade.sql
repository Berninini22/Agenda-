create table if not exists public.doctor_locations (
  doctor_id uuid not null references public.profiles(user_id) on delete cascade,
  location_id bigint not null references public.locations(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (doctor_id, location_id)
);
-- Slots recorrentes: weekday ISO (1=seg, 7=dom), turno e hora de início. Um slot é único por médico/dia/hora; locais e turnos podem ser associados explicitamente.
create table if not exists public.doctor_slots (
  id bigint generated by default as identity primary key,
  doctor_id uuid not null references public.profiles(user_id) on delete cascade,
  location_id bigint not null references public.locations(id) on delete cascade,
  weekday smallint not null check (weekday between 1 and 7),
  period text not null check (period in ('morning','afternoon','evening')),
  start_time time not null,
  end_time time not null,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  check (end_time > start_time),
  unique (doctor_id, location_id, weekday, start_time)
);
alter table public.appointments
  add column if not exists location_id bigint references public.locations(id) on delete set null,
  add column if not exists slot_id bigint references public.doctor_slots(id) on delete set null,
  add column if not exists updated_at timestamptz not null default now();

