create or replace function public.book_appointment(
  p_user_id uuid, p_doctor_id uuid, p_patient text, p_mode text,
  p_specialty text, p_professional text, p_unit text, p_date date,
  p_time time, p_location_id bigint default null, p_slot_id bigint default null
) returns public.appointments
language plpgsql security invoker set search_path = public
as $$
declare booked public.appointments;
begin
  if auth.uid() is null or auth.uid() <> p_user_id then raise exception 'unauthorized'; end if;
  if p_mode not in ('presencial','teleconsulta') then raise exception 'invalid_mode'; end if;
  if p_date < current_date then raise exception 'date_in_past'; end if;
  if p_doctor_id is null or not exists (select 1 from profiles where user_id=p_doctor_id and role='doctor') then raise exception 'doctor_unavailable'; end if;
  if p_location_id is not null and not exists (select 1 from doctor_locations where doctor_id=p_doctor_id and location_id=p_location_id) then raise exception 'location_not_assigned'; end if;
  insert into appointments(user_id,doctor_id,patient,mode,specialty,professional,unit,date_iso,time,location_id,slot_id,status)
  values(p_user_id,p_doctor_id,p_patient,p_mode,p_specialty,p_professional,p_unit,p_date,p_time,p_location_id,p_slot_id,'Confirmada') returning * into booked;
  return booked;
exception when unique_violation then raise exception 'slot_already_booked';
end; $$;

