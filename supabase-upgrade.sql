-- O aceite recebido no Auth é copiado para profiles pelo trigger já existente.
create or replace function public.handle_new_user_profile()
returns trigger language plpgsql security definer set search_path = public as $$
declare raw_role text := coalesce(new.raw_user_meta_data ->> 'role', 'patient');
begin
  if nullif(new.raw_user_meta_data ->> 'terms_accepted_at','') is null
     or nullif(new.raw_user_meta_data ->> 'terms_version','') is null then
    raise exception 'terms_acceptance_required';
  end if;
  if raw_role not in ('patient','doctor') then raw_role := 'patient'; end if;
  insert into public.profiles(user_id,role,full_name,crm,crm_state,specialty,phone,terms_accepted_at,terms_version)
  values(new.id,raw_role,coalesce(new.raw_user_meta_data ->> 'full_name',''),
    new.raw_user_meta_data ->> 'crm',new.raw_user_meta_data ->> 'crm_state',
    new.raw_user_meta_data ->> 'specialty',new.raw_user_meta_data ->> 'phone',
    now(),new.raw_user_meta_data ->> 'terms_version')
  on conflict(user_id) do nothing;
  return new;
end; $$;
drop trigger if exists on_auth_user_created_profile on auth.users;
create trigger on_auth_user_created_profile after insert on auth.users
for each row execute function public.handle_new_user_profile();

create or replace function public.prevent_client_terms_change()
returns trigger language plpgsql as $$
begin
  if auth.uid() is not null and (new.terms_accepted_at is distinct from old.terms_accepted_at or new.terms_version is distinct from old.terms_version) then
    raise exception 'terms_acceptance_is_immutable';
  end if;
  return new;
end; $$;
drop trigger if exists prevent_client_terms_change on public.profiles;
create trigger prevent_client_terms_change before update of terms_accepted_at,terms_version on public.profiles
for each row execute function public.prevent_client_terms_change();

